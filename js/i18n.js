let lang = "ru";
export function setLang(l) { lang = l === "en" ? "en" : "ru"; document.documentElement.lang = lang; }
export function getLang() { return lang; }
// t("ключ") → текст на текущем языке
export function t(key) {
  const v = T[key];
  if (!v) return key;
  return lang === "en" ? v[1] : v[0];
}
// tr({ru, en}) → текст из объекта с двумя языками
export function tr(obj) { return obj ? (lang === "en" ? obj.en : obj.ru) : ""; }
